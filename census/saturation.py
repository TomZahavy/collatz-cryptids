def order(b, M):
    o, p = 1, b % M
    while p != 1:
        p, o = (p * b) % M, o + 1
    return o


def mu_a(m, v, M):
    tw = pow(2, v + 1, M)
    mu = (m.A(v) * pow(tw, -1, M)) % M
    return mu, (m.B(v) - mu * pow(2, v, M)) % M


def full_image(m, c, M, vmax):
    out = set()
    for v in range(vmax):
        k = ((c - pow(2, v, M)) * pow(pow(2, v + 1, M), -1, M)) % M
        out.add((m.A(v) * k + m.B(v)) % M)
    return out


def separates(mach, M, x0=3):
    """Exactly decide.congruence_proof's test, for one modulus."""
    H = halt_residues(M)
    c0 = x0 % M
    if c0 in H:
        return False
    maps, edges = branch_maps(mach, M)
    adj = {}
    for s, t in edges:
        adj.setdefault(s, set()).add(t)
    reach, frontier = {c0}, [c0]
    while frontier:
        c = frontier.pop()
        for t in {(mu * c + a) % M for mu, a in maps} | adj.get(c, set()):
            if t in H:
                return False
            if t not in reach:
                reach.add(t)
                frontier.append(t)
    return True


def T3(a, b, g, d, e):
    return d % 3 == 0 and (g - a) % 3 == 0 and (b + e) % 3 == 0


def C4(a, b, g, d, e):
    return b % 2 == 0 and (2 * a + b + g + e) % 4 == 3


def C6(a, b, g, d, e):
    A0, B0 = 2 * a + b, g + e
    T = (A0 + B0) % 6
    return ((A0 % 2 == 0 and T == 3)
            or (A0 % 6 in (0, 4) and T == 5)
            or T3(a, b, g, d, e)
            or (A0 % 6 == 0 and B0 % 6 == 0 and d % 3 == 0
                and (g + d - b - 5) % 6 == 0))


def step1_saturation():
    print("STEP 1 -- T12, THE DELTA-SATURATION THEOREM: its proof steps")
    print("-" * 72)
    import random
    random.seed(3)
    tested = bad_ab = bad_c = 0
    while tested < 4000:
        t = (random.randint(1, 6), random.choice([-1, 1, 3, 5, 7, 2, 4]),
             random.randint(1, 6), random.randint(1, 6), random.randint(-3, 3))
        M = random.randrange(3, 400, 2)
        if gcd(t[3], M) != 1:
            continue
        o = order(2, M)
        if gcd(o, M) != 1:
            continue
        m, d = Machine(*t), t[3]
        tested += 1
        for v0 in range(min(o, 6)):
            mu0, a0 = mu_a(m, v0, M)
            for j in range(1, 12):
                v = v0 + j * o
                mu, a = mu_a(m, v, M)
                if mu != mu0 or (a - a0) % M != (d * (v - v0)) % M:
                    bad_ab += 1
        if len({(d * o * j) % M for j in range(M)}) != M:
            bad_c += 1
    print("  %d (machine, odd M) pairs meeting the hypotheses" % tested)
    print("  mu_v constant and a_v - a_v0 = delta(v-v0) on the class: "
          "%d violations" % bad_ab)
    print("  delta*ord*Z = Z_M under the hypotheses: %d violations" % bad_c)
    bad_d = n_d = 0
    random.seed(9)
    for _ in range(400):
        t = (random.randint(1, 5), random.choice([-1, 1, 3, 5, 2]),
             random.randint(1, 5), random.randint(1, 5), random.randint(-3, 3))
        M = random.randrange(3, 62, 2)
        if gcd(t[3], M) != 1 or gcd(order(2, M), M) != 1:
            continue
        n_d += 1
        if len(full_image(Machine(*t), random.randrange(M), M,
                          order(2, M) * M + 4)) != M:
            bad_d += 1
    print("  end-to-end: image = Z_M in %d cases with M < 62, %d failures"
          % (n_d, bad_d))
    return bad_ab == 0 and bad_c == 0 and bad_d == 0


def step2_needle():
    print("\nSTEP 2 -- COROLLARY: no odd prime separates the Space Needle")
    print("-" * 72)
    needle = Machine(1, 3, 1, 1, 0)
    primes = [p for p in range(3, 4000)
              if all(p % d for d in range(2, int(p ** .5) + 1))]
    hyp = sum(1 for p in primes
              if gcd(order(2, p), p) != 1 or gcd(1, p) != 1)
    small = [p for p in primes if p < 200]
    bad = sum(1 for p in small
              if len(full_image(needle, 3 % p, p, order(2, p) * p + 4)) != p)
    print("  %d odd primes below 4000; hypotheses fail for %d" % (len(primes), hyp))
    print("  end-to-end on the %d primes below 200: %d failures"
          % (len(small), bad))
    print("  (ord_p(2) | p-1, so the second hypothesis is automatic for primes)")
    return hyp == 0 and bad == 0


def step3_falsifier():
    print("\nSTEP 3 -- FALSIFIER: every separating certificate must break a")
    print("          hypothesis, or T12 is false")
    print("-" * 72)
    dec = [r for r in ROWS if r["cong"]]
    ref = ev = gd = 0
    for r in dec:
        m, d = int(r["cong"]), int(r["delta"])
        if m % 2 == 0:
            ev += 1
        elif gcd(d, m) != 1 or gcd(order(2, m), m) != 1:
            gd += 1
        else:
            ref += 1
    print("  %d machines decided by a congruence" % len(dec))
    print("    modulus even (T12 silent):            %d" % ev)
    print("    odd but a gcd hypothesis fails:       %d" % gd)
    print("    WOULD REFUTE T12:                     %d" % ref)
    return ref == 0


def step4_criteria():
    print("\nSTEP 4 -- C4 AND C6: complete on (Z_m)^5, then on the census")
    print("-" * 72)
    bad = 0
    for m, pred, name in ((4, C4, "C4"), (6, C6, "C6")):
        mism = sep = 0
        for tup in product(range(m), repeat=m and 5):
            got = separates(Machine(*tup), m)
            sep += got
            mism += (got != pred(*tup))
        bad += mism
        print("  %s: all %d residue tuples mod %d -- %d separate, %d mismatches"
              % (name, m ** 5, m, sep, mism))
    for r in ROWS:
        t = tuple(int(r[k]) for k in ("alpha", "beta", "gamma", "delta", "eps"))
        r["_t"] = t
        r["_sep"] = {s: separates(Machine(*t), s) for s in range(2, 7)}
    print("  against the census, all %d machines:" % len(ROWS))
    for m, pred, name in ((3, T3, "T3"), (4, C4, "C4"), (6, C6, "C6")):
        pd = nd = dn = 0
        for r in ROWS:
            here = bool(r["cong"]) and int(r["cong"]) == m
            p = pred(*r["_t"]) and not any(r["_sep"][s] for s in range(2, m))
            pd += p and here
            nd += p and not here
            dn += here and not p
        bad += nd + dn
        print("    %s (m = %d): predicted and decided %3d, predicted not "
              "decided %d, decided not predicted %d" % (name, m, pd, nd, dn))
    return bad == 0



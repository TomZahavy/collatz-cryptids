"""Why no congruence decides the Needle: a theorem, not a search bound.

WS4 swept every modulus m <= 20,000 and found no separating congruence for the
Space Needle.  That is a bounded resource -- exactly the kind of result P9 warns
is silent past its budget.  This file replaces an infinite slice of that sweep
with a proof, and adds the congruence-criterion theorems at m = 4, 6, 8 that the
census left on the table after T3 did m = 3.

NAMING.  T1, T2, T4-T11 are machines that never halt (theorems.py, leads.py,
universal.py).  T3 is the m = 3 separation criterion; C4, C6, C8 below are its
companions at 4, 6, 8.  T12 is the saturation theorem.

--------------------------------------------------------------------------
T12 -- THE DELTA-SATURATION THEOREM (proved).

  Let a machine have parameters (alpha, beta, gamma, delta, epsilon) and let M
  be ODD with gcd(delta, M) = 1 and gcd(ord_M(2), M) = 1.  Then for EVERY
  residue c, the one-step image {phi_v(c) : v >= 0} is ALL of Z_M.

PROOF.  M odd makes 2^(v+1) invertible, so branch v is the single affine map

    phi_v(c) = mu_v c + a_v,   mu_v = A_v (2^(v+1))^{-1},  a_v = B_v - mu_v 2^v

(the source is x = 2^(v+1) k + 2^v = c, so k = (c - 2^v)/2^(v+1), and the target
is A_v k + B_v).  Fix v0 and restrict to v = v0 (mod ord_M(2)).  On that class
2^v mod M is constant, hence A_v mod M is constant, hence mu_v is constant; and
gamma*2^v is constant too.  So the ONLY surviving v-dependence in a_v is the
term delta*v:

    a_v - a_{v0} = delta*(v - v0)        (mod M)

As v runs over v0 + ord_M(2)*Z, the difference v - v0 runs over ord_M(2)*Z,
whose image in Z_M is the subgroup generated by gcd(ord_M(2), M) = 1 -- that is,
all of Z_M.  And gcd(delta, M) = 1 makes delta*(v - v0) run over all of Z_M as
well.  Hence {phi_v(c)} contains mu_{v0} c + a_{v0} + Z_M = Z_M.  QED

COROLLARY (the Space Needle).  delta = 1, so gcd(delta, p) = 1 for every odd
prime p; and ord_p(2) divides p - 1, so gcd(ord_p(2), p) = 1 automatically.
**No odd prime modulus can ever separate the Needle** -- not "none below the
search bound": none, unconditionally.  In fact no branch can even be excluded,
since already the one-step image from any residue is everything.

This sharpens T3's corollary.  T3 said the v-linear term blocks the cheapest
certificate (m = 3).  T12 says it blocks EVERY prime certificate TOTALLY, in a
single step, for reasons that have nothing to do with how large the prime is.

WHAT IT DOES NOT COVER.  Even M.  That is not a gap in the write-up but the
honest boundary of the argument: 2 is not invertible mod an even M, so a branch
is no longer a single affine map.  It matters, because 274 of the census's 318
separating certificates live at even moduli -- if a certificate for a hard
machine exists at all, that is where it must be.

--------------------------------------------------------------------------
THE CONGRUENCE CRITERIA.  Separation at m depends on (alpha,...,epsilon) only
through their residues mod m, so each criterion is a finite object on (Z_m)^5
and is checked COMPLETELY below, not sampled.  Write

    A0 = 2a+b,  B0 = g+e,  A1 = 4a+b,  B1 = 2g+d+e,  T = A0+B0,  U = A1+B1.

 T3 (already proved).  Separates at 3  <=>  d = 0, g = a, b + e = 0  (mod 3).

 C4 (proved).  Separates at 4  <=>  b even and 2a+b+g+e = 3 (mod 4).
    Mod 4 the powers of two are {1,2,0}, so H = {0,1,2} and the only allowed
    class is {3}, which holds x0 = 3; the closure must therefore be exactly {3}.
    Only v = 0 has odd sources, and x = 2k+1 = 3 (mod 4) iff k is odd, giving
    the two targets A0+B0 and 3A0+B0.  Both equal 3 iff 2A0 = 0 (mod 4) -- i.e.
    A0 even, i.e. b even -- and A0+B0 = 3 (mod 4).

 C6 (proved).  H = {1,2,4}, allowed {0,3,5}.  Separates at 6 iff one of
    (a) A0 even and T = 3 (mod 6)                               [closure {3}]
    (b) A0 = 0 or 4 (mod 6) and T = 5 (mod 6)                   [closure {3,5}]
    (c) T3 holds                                                [closure in {0,3}]
    (d) A0 = 0, B0 = 0 (mod 6), d = 0 (mod 3), g+d = b+5 (mod 6) [{0,3,5}]
    From 3 the targets are {T, T+3A0} and 3A0 is 0 or 3, so a subset of {0,3,5}
    forces {0,3}; that is (a).  From 5 they are {T+A0, T+4A0}; that is (b).  If
    0 is reached but 5 is not, all twelve targets out of 0 must lie in {0,3},
    i.e. A_v + B_v = 0 (mod 3) for all six v-classes, which forces d = 0, then
    g = a, then b + e = 0 (mod 3) -- exactly T3.  (d) is the residue.

 C8 (proved).  H = {0,1,2,4}, allowed {3,5,6,7}.  Only v = 0 and v = 1 can
    occur (v = 2 gives source 4, v >= 3 gives source 0, both halting).  A0 must
    be even: if A0 is odd, from 3 the targets are {T, T+4}, admissible only as
    {3,7}, and then from 7 the targets {T+2, T+6} always contain 1.  With A0
    even, 4A0 = 0 (mod 8) and the question is the forward orbit of 3 under the
    explicit four-node map 3 -> T, 5 -> T+A0, 7 -> T+2A0,
    6 -> {U + 2jA1 : j = 0..3}.

--------------------------------------------------------------------------
PROVENANCE.  T12 came out of asking why Bertok-Hajdu's Skolem-witness machinery
finds nothing here.  It does not apply -- their equations admit only exponents
as unknowns, and ours carry k and delta*v linearly -- but the question "why does
no witness modulus exist?" is better than "which witness works?", and this is
its answer.  The Skolem framing is a good orienting remark and not a tool; see
the meta report.
"""

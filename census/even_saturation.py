def v2(n):
    c = 0
    while n % 2 == 0:
        n //= 2
        c += 1
    return c


def factor(n):
    f, d = {}, 2
    while d * d <= n:
        while n % d == 0:
            f[d] = f.get(d, 0) + 1
            n //= d
        d += 1
    if n > 1:
        f[n] = f.get(n, 0) + 1
    return f


def carmichael(n):
    """lambda(n) for odd n (all we need here)."""
    lam = 1
    for p, e in factor(n).items():
        lp = (p - 1) * p ** (e - 1)
        lam = lam * lp // gcd(lam, lp)
    return lam


def order2(n):
    """ord_n(2) for odd n > 1, via lambda then stripping primes."""
    if n == 1:
        return 1
    t = carmichael(n)
    for q in factor(t):
        while t % q == 0 and pow(2, t // q, n) == 1:
            t //= q
    return t


def closure(mach, M, x0=3):
    maps, edges = branch_maps(mach, M)
    adj = {}
    for s_, t_ in edges:
        adj.setdefault(s_, set()).add(t_)
    reach, frontier = {x0 % M}, [x0 % M]
    while frontier:
        c = frontier.pop()
        for t_ in {(mu * c + a) % M for mu, a in maps} | adj.get(c, set()):
            if t_ not in reach:
                reach.add(t_)
                frontier.append(t_)
    return reach


def tup(r):
    return tuple(int(r[k]) for k in ("alpha", "beta", "gamma", "delta", "eps"))


def step1_mechanism():
    print("STEP 1 -- THE MECHANISM: an even modulus reads the valuation off the")
    print("          low bits, for v < s and only there")
    print("-" * 72)
    bad = tested = 0
    for s in range(1, 9):
        for c in range(1, 1 << s):
            v = v2(c)
            if v >= s:
                continue
            tested += 1
            # every x = c (mod 2^s) has v_2(x) = v exactly
            for j in range(40):
                x = c + j * (1 << s)
                if x and v2(x) != v:
                    bad += 1
    print("  residues c mod 2^s with v_2(c) = v < s pin v exactly:")
    print("  %d residues checked over s = 1..8, 40 lifts each: %d failures"
          % (tested, bad))
    print("  and c = 0 (mod 2^s) pins nothing -- every v >= s is available.")
    return bad == 0


def step2_proof_steps():
    print("\nSTEP 2 -- T14's PROOF STEPS")
    print("-" * 72)
    import random
    random.seed(17)
    n = bad_free = bad_det = bad_sweep = 0
    while n < 3000:
        t = (random.randint(1, 6), random.choice([-1, 1, 3, 5, 7]),
             random.randint(1, 6), random.randint(1, 6), random.randint(-3, 3))
        s = random.randint(1, 6)
        Mp = random.randrange(1, 60, 2)
        M = (1 << s) * Mp
        if gcd(t[3], Mp) != 1 or (Mp > 1 and gcd(order2(Mp), Mp) != 1):
            continue
        m = Machine(*t)
        n += 1
        v = s + random.randint(0, 5)
        c0 = (random.randrange(Mp) * (1 << s)) % M       # c0 = 0 mod 2^s
        # (a) k unconstrained mod 2^s, determined mod M'
        ks = [k for k in range(M)
              if ((1 << (v + 1)) * k + (1 << v) - c0) % M == 0]
        if len({k % (1 << s) for k in ks}) != (1 << s):
            bad_free += 1
        if len({k % Mp for k in ks}) != 1:
            bad_det += 1
        # (b) the 2-adic component of the targets sweeps all of Z_{2^s}
        if len({(m.A(v) * k + m.B(v)) % (1 << s) for k in ks}) != (1 << s):
            bad_sweep += 1
    print("  %d (machine, s, M', v >= s) instances meeting the hypotheses" % n)
    print("  k unconstrained mod 2^s:                    %d failures" % bad_free)
    print("  k determined mod M':                        %d failures" % bad_det)
    print("  targets sweep all of Z_(2^s) (beta a unit): %d failures" % bad_sweep)
    return bad_free == bad_det == bad_sweep == 0


def step3_conclusion():
    print("\nSTEP 3 -- THE CONCLUSION: closure = Z_M whenever (i)-(iv) hold")
    print("-" * 72)
    tested = notall = skipped_iv = 0
    for r in ROWS:
        t = tup(r)

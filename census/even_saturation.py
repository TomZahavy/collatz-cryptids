def step6_sharp():
    """T14': the simplifications, and the coset-covering equivalence."""
    print("\nSTEP 6 -- T14', THE SHARP FORM: a_v = B_v - A_v/2, and an IFF")
    print("-" * 72)
    import random
    random.seed(4)
    bad_a = bad_red = n = 0
    while n < 4000:
        t = (random.randint(1, 6), random.choice([-1, 1, 3, 5, 7]),
             random.randint(1, 6), random.randint(1, 6), random.randint(-3, 3))
        Mp = random.randrange(3, 200, 2)
        if gcd(t[3], Mp) != 1:
            continue
        m, n = Machine(*t), n + 1
        inv2 = pow(2, -1, Mp)
        for v in range(30):
            iv = pow(pow(2, v + 1, Mp), -1, Mp)
            mu = (m.A(v) * iv) % Mp
            if (m.B(v) - mu * pow(2, v, Mp)) % Mp != (m.B(v) - m.A(v) * inv2) % Mp:
                bad_a += 1
            if mu != (t[0] + t[1] * iv) % Mp:
                bad_a += 1
        ordv, c = order2(Mp), random.randrange(Mp)
        g = gcd(ordv, Mp)
        S = {((m.A(v) * pow(pow(2, v + 1, Mp), -1, Mp)) * c
              + m.B(v) - m.A(v) * inv2) % Mp
             for v in range(ordv * Mp + ordv + 4)}
        base = {(((m.A(v0) * pow(pow(2, v0 + 1, Mp), -1, Mp)) * c
                  + m.B(v0) - m.A(v0) * inv2) % Mp) % g for v0 in range(ordv)}
        if (len(base) == g) != (len(S) == Mp):
            bad_red += 1
    print("  a_v = B_v - A_v/2 and mu_v = alpha + beta/2^(v+1): %d violations"
          % bad_a)
    print("  (iii') 'S = Z_M' iff the ord base points cover the g cosets':")
    print("     %d (machine, M') instances, %d mismatches" % (n, bad_red))
    return bad_a == 0 and bad_red == 0



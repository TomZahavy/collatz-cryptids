def step4_falsifier():
    print("\nSTEP 4 -- FALSIFIER: every EVEN-modulus certificate must break a")
    print("          hypothesis, or T14 is false")
    print("-" * 72)
    even = [r for r in ROWS if r["cong"] and int(r["cong"]) % 2 == 0]
    b_even = i_fail = ii_fail = iii_fail = iv_fail = refute = 0
    for r in even:
        t = tup(r)
        M = int(r["cong"])
        s, Mp = v2(M), M >> v2(M)
        if t[1] % 2 == 0:
            b_even += 1
            i_fail += 1
            continue
        if gcd(t[3], Mp) != 1:
            ii_fail += 1
        elif Mp > 1 and gcd(order2(Mp), Mp) != 1:
            iii_fail += 1
        elif not any(c % (1 << s) == 0 for c in closure(Machine(*t), M)):
            iv_fail += 1
        else:
            refute += 1
    print("  %d certificates at even moduli" % len(even))
    print("    (i) beta even  -- the escape hatch:      %d" % i_fail)
    print("    (ii) gcd(delta, M') > 1 (all have delta = 0): %d" % ii_fail)
    print("    (iii) gcd(ord_M'(2), M') > 1:            %d" % iii_fail)
    print("    (iv) no 2-adic reach:                    %d" % iv_fail)
    print("    WOULD REFUTE T14:                        %d" % refute)
    print("  (so every even-modulus certificate in the census is buying exactly")
    print("   the beta-even hatch, or is a delta = 0 machine)")
    return refute == 0



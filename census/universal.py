def step3_orders():
    """Classify each (alpha,beta) class by the size of <2> mod A_v.

    The silence test is EXPANSION, not the order computation: the sieve argues
    from a branch's affine fixed point, so a branch with A_v <= 2^(v+1) gives it
    nothing to say.  That is why the whole (1,-1) class is silent -- its orders
    are perfectly small, but no branch of it expands.
    """
    print("STEP 3 -- WHY SOME CLASSES ARE DECIDABLE BY HAND: the size of <2>")
    print("-" * 74)
    print("  %-9s %-26s %s" % ("(a,b)", "ord_{A_v}(2), v = 0..7", "kind"))
    kinds = {}
    for a, b in product(ALPHAS, BETAS):
        m = Machine(a, b, 1, 0, 0)
        ords = [order_of_2(m.A(v)) if m.A(v) > 1 and m.A(v) % 2 else None
                for v in range(8)]
        if all(m.branch_sieve_data(v) is None for v in range(SWEEP_VMAX + 1)):
            kind = "silent (no expanding branch)"
        elif all(o is not None and o <= 8 * (v + 2) for v, o in enumerate(ords)):
            kind = "LISTABLE"
        else:
            kind = "thin"
        kinds[(a, b)] = kind
        print("  %-9s %-26s %s"
              % ("(%d,%d)" % (a, b),
                 ",".join("-" if o is None else str(o) for o in ords), kind))
    print()
    return kinds


def baby_tables():
    """One shared BSGS table per (alpha,beta,v): A_v depends only on those."""
    tables = {}
    for a, b in product(ALPHAS, BETAS):
        mm = Machine(a, b, 1, 0, 0)
        for v in range(SWEEP_VMAX + 1):
            A = mm.A(v)
            if A < 3 or A % 2 == 0:
                continue
            M = isqrt(A) + 1
            baby, p = {}, 1 % A
            for j in range(M):
                baby.setdefault(p, j)
                p = (p * 2) % A
            tables[(a, b, v)] = (baby, M, pow(pow(2, M, A), -1, A))
    return tables


def step4_sweep(box, tables):
    """Every machine: forbidden mass, and an explicit surviving branch if any."""
    print("STEP 4 -- THE COMPLETENESS SWEEP (v <= %d, shared baby tables)" % SWEEP_VMAX)
    print("-" * 74)
    allforb, survivors, silent = [], {}, []
    for t, m in box:
        a, b = t[0], t[1]
        tested = forb = 0
        witness = None
        for v in range(SWEEP_VMAX + 1):
            S = target(m, v)
            if S is None:
                continue
            tested += 1
            baby, M, giant = tables[(a, b, v)]
            e = pow2_witness(S, m.A(v), baby, M, giant)
            if e is None:
                forb += 1
            elif witness is None:
                witness = (v, e, S, m.A(v))
        if tested == 0:
            silent.append(t)
        elif witness is None:
            allforb.append(t)
        else:
            survivors[t] = witness
    print("  machines swept: %d" % len(box))
    print("  sieve-silent (no expanding branch, sieve says nothing): %d" % len(silent))
    print("  with an EXPLICIT surviving branch (positive certificate): %d"
          % len(survivors))
    print("  with every branch forbidden: %d" % len(allforb))
    ok = True
    for t in allforb:
        if t not in THEOREMS:
            print("  *** UNCLAIMED all-forbidden machine %s -- investigate" % (t,))
            ok = False
    for t in THEOREMS:
        if t not in allforb:
            print("  *** claimed theorem %s has a surviving branch -- WRONG" % (t,))
            ok = False
    print("  matches the ten claimed machines exactly: %s" % ("yes" if ok else "NO"))
    ex = sorted(survivors)[0]
    v, e, S, A = survivors[ex]
    print("  sample certificate: %s survives at v = %d, 2^%d = %d (mod %d): %s"
          % (str(ex), v, e, S, A, pow(2, e, A) == S % A))
    print()
    return allforb, survivors, silent, ok


def step5_closed_forms(allforb):
    print("STEP 5 -- THE TEN MACHINES: closed forms asserted, every branch forbidden")
    print("-" * 74)
    print("  %-17s %-5s %-19s %-4s %s"
          % ("machine", "name", "S_v (derived)", "pat", "branches forbidden, v <= %d" % DEEP_VMAX))
    ok = True
    for t in sorted(THEOREMS, key=lambda k: int(THEOREMS[k][0][1:])):
        name, form, f, pat = THEOREMS[t]
        m = Machine(*t)
        mism = surv = tested = 0
        for v in range(DEEP_VMAX + 1):
            S = target(m, v)
            if S is None:
                continue
            tested += 1
            A = m.A(v)
            if S != f(v) % A:
                mism += 1
            pows, p = set(), 1 % A
            while p not in pows:            # orders here are O(v): cheap
                pows.add(p)
                p = (p * 2) % A
            if S in pows:
                surv += 1
        if mism or surv:
            ok = False
        print("  %-17s %-5s %-19s %-4s %s"
              % (str(t), name, form, pat,
                 "all %d forbidden" % tested if not surv
                 else "%d SURVIVE" % surv)
              + ("" if not mism else "   %d FORM ERRORS" % mism))
    print()
    return ok


def step6_brute(allforb):
    print("STEP 6 -- BRUTE FORCE: no orbit reaches a power of two after >= 1 step")
    print("-" * 74)
    print("  (starts that ARE powers of two halt at step 0 and are excluded)")
    total = 0
    for t in sorted(THEOREMS, key=lambda k: int(THEOREMS[k][0][1:])):
        m, bad = Machine(*t), 0
        for x0 in range(2, 20000):
            if x0 & (x0 - 1) == 0:
                continue
            x = x0
            for _ in range(400):
                y = m.step(x)
                if y == "HALT":
                    bad += 1
                    break
                if y.bit_length() > 6000:
                    break
                x = y
        total += bad
        print("  %-5s %-17s starts 2..19999, 400 steps: halts = %d"
              % (THEOREMS[t][0], str(t), bad))
    print("  total counterexamples: %d\n" % total)
    return total == 0



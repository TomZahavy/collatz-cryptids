def machines():
    """Every well-defined odd-beta member of the census box."""
    out = []
    for t in product(ALPHAS, BETAS, GAMMAS, DELTAS, EPSS):
        m = Machine(*t)
        if m.well_defined():
            out.append((t, m))
    return out


def target(mach, v):
    """S_v from the sieve's own fixed-point data, or None if the sieve is silent."""
    data = mach.branch_sieve_data(v)
    if data is None:
        return None
    _, _, P, Q, _ = data
    A = mach.A(v)
    return (2 * (P * pow(Q, -1, A))) % A


def order_of_2(A):
    o, p = 1, 2 % A
    while p != 1:
        p, o = (p * 2) % A, o + 1
    return o


def pow2_witness(S, A, baby, M, giant):
    """The exponent e with 2^e = S (mod A), or None.  Baby table is shared
    across all machines of an (alpha,beta,v) class -- A depends only on those."""
    S %= A
    if S == 0:
        return None
    y = S
    for i in range(M + 1):
        j = baby.get(y)
        if j is not None:
            return i * M + j
        y = (y * giant) % A
    return None


def step1_lemma(box):
    print("STEP 1 -- THE UNIVERSAL LEMMA:  S_v = 2 B_v (mod A_v), beta odd")
    print("-" * 74)
    bad = tested = live = 0
    for _, m in box:
        seen = False
        for v in range(LEMMA_VMAX + 1):
            S = target(m, v)
            if S is None:
                continue
            seen = True
            tested += 1
            if S != (2 * m.B(v)) % m.A(v):
                bad += 1
        live += seen
    print("  %d machines (%d with a non-silent sieve), %d branches, v = 0..%d"
          % (len(box), live, tested, LEMMA_VMAX))
    print("  mismatches: %d  ->  %s\n"
          % (bad, "lemma holds" if bad == 0 else "LEMMA FALSE -- stop here"))
    return bad == 0


